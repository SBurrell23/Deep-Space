/**
 * Deep Space - core and nose parts for composed duelist hulls.
 *
 * Each part is the TOP HALF of a 64x40 sprite: twenty rows of sixty-four
 * characters, mirrored about the centre line by the composer, so row 19 touches
 * the mirror and row 0 is the sprite's top edge. Hulls face LEFT.
 *
 * Because the composer mirrors, no part can carry a top-lit, bottom-shadowed
 * gradient - it would fold back on itself and read as a smear. The light runs
 * along the hull instead: bright at the leading edge, falling away toward the
 * engines, with 'w' kept to the top-left rim and nowhere else.
 *
 * The fourteen cores are fourteen different SHAPES rather than one wedge shaded
 * fourteen ways. A hundred ships share this handful of fuselages, so a
 * silhouette that is merely restyled reads as a repeat the moment two of them
 * turn up in the same run - hence ring is a real torus you can see stars
 * through, lattice is open framework, husk is holed, and spindle widens toward
 * the back. For the same reason the accent ramp is used thinly here: a canopy,
 * the odd stripe. Pods, wings and crests carry a ship's own detail, and a loud
 * core would drown them out.
 *
 * Noses stay inside x 0-20 so the core still reads behind them. sensor_dome and
 * cowl are the two allowed above the shoulder line, because a dome that does
 * not break the hull's profile is just a painted circle.
 */
