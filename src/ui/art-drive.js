/**
 * Deep Space - engine and pod overlays for the composed duelist sprite.
 *
 * These are the fourth and fifth layers of core -> nose -> wing -> pod ->
 * engine -> crest, so they are painted over a fuselage that is already a
 * finished ship. Every row here is mostly dots on purpose: a solid rectangle
 * would delete the hull it is supposed to be bolted to, and the composer has
 * no way to tell that apart from deliberate art.
 *
 * Engines are held to x >= 44 and pods to the midships band because the
 * vocabulary is combinatorial - any engine has to sit behind any core without
 * being consulted about it, and the only thing keeping a bell off a nose is
 * that no engine ever paints that far forward.
 *
 * Only rows 0-19 exist; the composer mirrors them about the centre line. So a
 * single cone drawn off-axis becomes a matched pair, which is why twin_cone,
 * side_barbettes and twin_lasers each draw exactly one of the thing they are
 * named for, and why anything meant to be single - single_bell, the middle of
 * stacked_trio, gatling_ring - is drawn hard against row 19 with no bottom
 * outline. An outline on row 19 mirrors into a black seam down the spine.
 *
 * Pods carry a k outline the whole way round. Without it a turret reads as a
 * hole punched in the hull rather than hardware sitting on top of it.
 */

