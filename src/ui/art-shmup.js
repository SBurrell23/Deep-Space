/**
 * Deep Space - hand-authored pixel art for the side-scrolling shooter layer.
 *
 * Same format and same discipline as art-ships.js: a palette map plus rows of
 * equal-length strings, '.' transparent, every other char an index into the
 * sprite's own palette.
 *
 * ORIENTATION
 *   The player flies on the LEFT and shoots RIGHT.
 *   Enemies come from the RIGHT and shoot LEFT.
 *   So every enemy hull faces LEFT (nose/guns on the left edge) and every
 *   player-owned thing (player bullets, dash streak, muzzle flash) faces RIGHT.
 *
 * LIGHT
 *   Top-left highlight, bottom-right shadow, exactly as art-ships.js.
 *
 * COLOUR IS GAMEPLAY
 *   Player ordnance is cyan/white. Enemy ordnance is red/amber/purple. Never
 *   mix the two - the player has to read incoming danger at a glance.
 *
 * Shared shading ramp (dark -> light): k d p 1 2 3 4 w
 * Accent ramps: e c C (ion/cyan)  o a A (amber)  x r R (red)
 *               n g G (green)     v u U (purple)  s q Q (pale ice blue)
 */
