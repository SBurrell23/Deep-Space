/**
 * Deep Space - wing and crest overlays for the composed duelist sprites.
 *
 * These are parts three and six of the six-part composer, authored as the top
 * half of a 64x40 sprite: exactly 20 rows of exactly 64 characters, mirrored
 * about the centre line at compose time. Row 19 sits against that centre line,
 * row 0 is the top edge, and the hull faces LEFT - nose at low x, engines at
 * high x - so the light still falls from the top-left.
 *
 * OVERLAYS, NOT SPRITES
 *   A wing or a crest is painted over a finished core. Every non-'.' character
 *   it carries deletes a pixel of the ship underneath, so both vocabularies are
 *   deliberately sparse: the busiest wing here covers under a quarter of the
 *   canvas and every crest under six per cent. Filling the canvas would erase
 *   the fuselage and every part would compose into the same blob.
 *
 * WHY THE WINGS CLIMB
 *   Wings live in x 14-52 and reach up into rows 2-15, well clear of the hull's
 *   own rows 16-19. A wing drawn level with the fuselage reads as a stripe
 *   painted on the side; one that stands proud of it reads as a wing, and it is
 *   the only part that changes a duelist's silhouette from across the field.
 *   Where a planform would otherwise float, a short root at rows 16-17 ties it
 *   back to the hull - a dozen pixels, no more.
 *
 * WHY THE CRESTS GLOW
 *   Crests are drawn last of the six, so nothing overpaints them and they are
 *   the one place bright accent and glow ('A', 'G') can be spent freely on
 *   lamps, aerial tips and vent throats. They are held to about twelve columns
 *   and the top half of the canvas: a crest is a name badge, not a hat.
 *
 * Shading follows the cores - 'k' outline, ramp '1' -> '4' -> 'w' running away
 * from the lit top-left corner of each run, 'w' spent only where a surface is
 * broad enough to catch a real highlight. Struts narrower than three pixels
 * keep the ramp instead of an outline, or an open frame renders as a black bar.
 */

